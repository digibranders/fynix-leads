import { sql } from "drizzle-orm";
import { boolean, check, date, foreignKey, index, integer, jsonb, pgTable, text, timestamp, unique, uuid } from "drizzle-orm/pg-core";
import type { QualifyingItem } from "@/lib/qualifying-items";
import { clientContact } from "./client-contact";
import { campaignStatus, organisationKind } from "./enums";
import { organisation } from "./organisation";

/**
 * One client, served by one coordinator (an agency with no parent; `agency_org_id` is the coordinator since phase 1D). Both organisation ids live here so a policy can compare one column per role.
 *
 * - The client never gets a grant on `agency_org_id`, and the agency never gets one on `client_org_id`.
 * - `client_org_kind` and `agency_org_kind` are constants. The composite foreign keys below use them to make the
 *   database refuse a client id that points at an agency, or the other way round.
 * - An agency reads the client's name through `app_campaign_client_name(campaign.id)` (migration 0078), which answers only for the campaigns it serves.
 */
export const campaign = pgTable(
  "campaign",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    /** `CMP-` and four base-32 characters, generated by the server. */
    publicRef: text("public_ref").notNull(),
    name: text("name").notNull(),
    clientOrgId: uuid("client_org_id").notNull(),
    clientOrgKind: organisationKind("client_org_kind").notNull().generatedAlwaysAs(sql`'client'::organisation_kind`),
    agencyOrgId: uuid("agency_org_id").notNull(),
    agencyOrgKind: organisationKind("agency_org_kind").notNull().generatedAlwaysAs(sql`'agency'::organisation_kind`),
    /** Fynix only. No tenant role has a grant on this column. */
    internalNotes: text("internal_notes"),
    status: campaignStatus("status").notNull().default("draft"),
    startDate: date("start_date", { mode: "string" }).notNull(),
    endDate: date("end_date", { mode: "string" }).notNull(),
    monthlyTarget: integer("monthly_target").notNull(),
    totalTarget: integer("total_target").notNull(),
    /**
     * What the campaign looks for and how to pitch it (spec section 6). Added in phase 1C, all with defaults so existing rows
     * stay valid. No tenant role has a grant on any of them until phase 1E decides who sees which; until then a tenant
     * query that names one fails with "permission denied" (the leak matrix probes it).
     */
    geography: text("geography").notNull().default(""),
    industries: text("industries").array().notNull().default(sql`'{}'::text[]`),
    companySize: text("company_size").notNull().default(""),
    icp: text("icp").notNull().default(""),
    jobTitles: text("job_titles").array().notNull().default(sql`'{}'::text[]`),
    seniority: text("seniority").notNull().default(""),
    technologies: text("technologies").array().notNull().default(sql`'{}'::text[]`),
    /** The four BANT criteria a lead is qualified against: budget, authority, need and timeline. */
    bantBudget: text("bant_budget").notNull().default(""),
    bantAuthority: text("bant_authority").notNull().default(""),
    bantNeed: text("bant_need").notNull().default(""),
    bantTimeline: text("bant_timeline").notNull().default(""),
    instructions: text("instructions").notNull().default(""),
    /**
     * The campaign's time zone, the one that counting uses (spec 7.1), and the default meeting length. Added in phase 1D with
     * defaults so existing rows stay valid. The domain validates the zone against the IANA database
     * (lib/domain/campaign-settings.ts); the database only checks the length. No tenant role has a grant on either until 1E.
     */
    timeZone: text("time_zone").notNull().default("Europe/London"),
    meetingMinutes: integer("meeting_minutes").notNull().default(30),
    /**
     * The client's own privacy page, named under the signature of every prospect letter (phase 6). https only. Fynix writes it; the client reads it; no agency does.
     * `prospect_email_enabled` is the switch that lets the portal email prospects of this campaign at all: it stays off until the link is set (the check below).
     */
    clientPrivacyUrl: text("client_privacy_url"),
    prospectEmailEnabled: boolean("prospect_email_enabled").notNull().default(false),
    /**
     * The campaign's own opening paragraph for the confirmation letter to prospects (rules in lib/email/letter-opening.ts). Null means the default wording.
     * Fynix alone reads and writes it; the letter takes it from the database when it is queued (`app_prospect_letter_opening`).
     */
    prospectLetterOpening: text("prospect_letter_opening"),
    /**
     * What Fynix takes when it sets a campaign up (migration 0083): how the client introduces itself to prospects, what it sells, what sets it
     * apart, its collaterals and case studies, the questions the sales team asks to qualify a prospect, and the two emails sent to prospects.
     * All free text. Fynix only: no tenant role has a grant on any of them yet.
     */
    pitchIntroduction: text("pitch_introduction").notNull().default(""),
    pitchServices: text("pitch_services").notNull().default(""),
    pitchDifferentiator: text("pitch_differentiator").notNull().default(""),
    pitchCollaterals: text("pitch_collaterals").notNull().default(""),
    pitchCaseStudies: text("pitch_case_studies").notNull().default(""),
    qualifyingQuestions: text("qualifying_questions").notNull().default(""),
    /**
     * The same questions as a list, each with the answer hoped for, both as rich text (migration 0110). When it is empty the old single text box above
     * is shown instead, one question per line, so campaigns set up before it keep their questions.
     */
    qualifyingItems: jsonb("qualifying_items").$type<QualifyingItem[]>().notNull().default([]),
    firstEmail: text("first_email").notNull().default(""),
    secondEmail: text("second_email").notNull().default(""),
    /** The person at the client who approves leads and gives feedback for this campaign: one of the client's contact people. Null until chosen. */
    primaryContactId: uuid("primary_contact_id"),
    /** When the campaign last moved into a closed status (paused, completed or archived); null while it is not closed. */
    closedAt: timestamp("closed_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    unique("campaign_public_ref_unique").on(table.publicRef),
    // The target of phase 2's composite foreign key from `lead`, which keeps a lead's two organisation ids equal
    // to its campaign's.
    unique("campaign_id_orgs_unique").on(table.id, table.clientOrgId, table.agencyOrgId),
    // The target of `campaign_host`'s composite foreign key, which pins a host to the campaign's own client (phase 1D).
    unique("campaign_id_client_unique").on(table.id, table.clientOrgId),
    foreignKey({
      name: "campaign_client_org_fk",
      columns: [table.clientOrgId, table.clientOrgKind],
      foreignColumns: [organisation.id, organisation.kind],
    }),
    foreignKey({
      name: "campaign_agency_org_fk",
      columns: [table.agencyOrgId, table.agencyOrgKind],
      foreignColumns: [organisation.id, organisation.kind],
    }),
    foreignKey({ name: "campaign_primary_contact_fk", columns: [table.primaryContactId, table.clientOrgId], foreignColumns: [clientContact.id, clientContact.clientOrgId] }),
    index("campaign_client_org_idx").on(table.clientOrgId),
    index("campaign_agency_org_idx").on(table.agencyOrgId),
    check("campaign_public_ref_format", sql`${table.publicRef} ~ '^CMP-[0-9A-HJKMNP-TV-Z]{4}$'`),
    check("campaign_dates_in_order", sql`${table.endDate} >= ${table.startDate}`),
    check("campaign_targets_not_negative", sql`${table.monthlyTarget} >= 0 AND ${table.totalTarget} >= 0`),
    check("campaign_meeting_minutes_range", sql`${table.meetingMinutes} BETWEEN 15 AND 240`),
    check("campaign_privacy_url_https", sql`${table.clientPrivacyUrl} IS NULL OR (${table.clientPrivacyUrl} ~ '^https://[^[:space:]]+$' AND char_length(${table.clientPrivacyUrl}) <= 500)`),
    check("campaign_letter_opening_length", sql`${table.prospectLetterOpening} IS NULL OR char_length(btrim(${table.prospectLetterOpening})) BETWEEN 1 AND 600`),
    check("campaign_prospect_email_needs_privacy_url", sql`NOT ${table.prospectEmailEnabled} OR ${table.clientPrivacyUrl} IS NOT NULL`),
    check("campaign_time_zone_length", sql`char_length(btrim(${table.timeZone})) BETWEEN 1 AND 64`),
  ],
);
