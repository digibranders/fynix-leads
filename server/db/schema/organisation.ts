import { check, foreignKey, index, pgTable, text, timestamp, unique, uniqueIndex, uuid } from "drizzle-orm/pg-core";
import { sql } from "drizzle-orm";
import { organisationKind, organisationStatus } from "./enums";

/**
 * Fynix itself, the client companies and the agencies. A tenant role reads only its own row, and never the `id`
 * column: the server knows the organisation id from the session, and no query a tenant can write returns one.
 */
export const organisation = pgTable(
  "organisation",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    /** The reference that is safe to show: `ORG-` and four base-32 characters, generated by the server. */
    publicRef: text("public_ref").notNull(),
    kind: organisationKind("kind").notNull(),
    name: text("name").notNull(),
    status: organisationStatus("status").notNull().default("active"),
    /**
     * The supplier a partner agency works under. Null for Fynix, every client and every supplier. A supplier is an agency with
     * no parent; a partner agency is an agency whose parent is a supplier; two levels at most (migration 0020 refuses a grandparent).
     * Added in phase 1D, nullable, so existing rows stay valid. No tenant role has a grant on it until phase 1E.
     */
    parentOrgId: uuid("parent_org_id"),
    /** `agency` while a parent is set, else null. The composite foreign key below uses it to insist the parent is an agency. */
    parentOrgKind: organisationKind("parent_org_kind").generatedAlwaysAs(sql`CASE WHEN parent_org_id IS NULL THEN NULL ELSE 'agency'::organisation_kind END`),
    /** The IANA zone the company works in, shown to the people who book meetings with it. Null until Fynix sets it. */
    timeZone: text("time_zone"),
    /**
     * Company contact details, written by a Fynix admin and read by Fynix only (migration 0080). No tenant role holds a grant on any of them,
     * and none is in a tenant column list in server/db/columns.ts. `notes` are internal.
     */
    contactName: text("contact_name"),
    contactEmail: text("contact_email"),
    contactPhone: text("contact_phone"),
    website: text("website"),
    address: text("address"),
    notes: text("notes"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    unique("organisation_public_ref_unique").on(table.publicRef),
    // The target of the composite foreign keys that pin a campaign's two organisations to the right kind.
    unique("organisation_id_kind_unique").on(table.id, table.kind),
    check("organisation_public_ref_format", sql`${table.publicRef} ~ '^ORG-[0-9A-HJKMNP-TV-Z]{4}$'`),
    // There is exactly one Fynix organisation. `pnpm admin:create` finds it or creates it, and member rows of kind
    // `fynix` point at it.
    uniqueIndex("organisation_one_fynix").on(table.kind).where(sql`${table.kind} = 'fynix'`),
    // The foreign key is not checked while `parent_org_kind` is null, so only an organisation with a parent is constrained.
    foreignKey({ name: "organisation_parent_fk", columns: [table.parentOrgId, table.parentOrgKind], foreignColumns: [table.id, table.kind] }),
    check("organisation_parent_not_self", sql`${table.parentOrgId} IS NULL OR ${table.parentOrgId} <> ${table.id}`),
    check("organisation_parent_only_agency", sql`${table.parentOrgId} IS NULL OR ${table.kind} = 'agency'`),
    index("organisation_parent_idx").on(table.parentOrgId),
    check("organisation_contact_name_length", sql`${table.contactName} IS NULL OR char_length(${table.contactName}) BETWEEN 1 AND 120`),
    check("organisation_contact_email_length", sql`${table.contactEmail} IS NULL OR char_length(${table.contactEmail}) BETWEEN 3 AND 254`),
    check("organisation_contact_phone_length", sql`${table.contactPhone} IS NULL OR char_length(${table.contactPhone}) BETWEEN 3 AND 40`),
    check("organisation_website_https", sql`${table.website} IS NULL OR (${table.website} ~ '^https://' AND char_length(${table.website}) <= 2000)`),
    check("organisation_address_length", sql`${table.address} IS NULL OR char_length(${table.address}) BETWEEN 1 AND 500`),
    check("organisation_notes_length", sql`${table.notes} IS NULL OR char_length(${table.notes}) BETWEEN 1 AND 4000`),
  ],
);
